def orci(m: dict, k: str) -> str:
    e = (m.get("effects") or {}).get(k)
    if not e:
        return "—"
    return f"{e['odds_ratio']:.2f} [{e['CI95_lower']:.2f}, {e['CI95_upper']:.2f}]"


def p(x: float) -> str:
    return "< .001" if x < 0.001 else f"{x:.3f}".replace("0.", ".", 1)


def status(m: dict) -> str:
    if "error" in m:
        return "error"
    s = "converged" if m["converged"] else f"NOT converged ({m['optimizer']})"
    return s + (", singular" if m["singular"] else "")


